// Copies the DGTL brand kit's spark and wordmark into lib/passes/brandAssets.js.
//
// The platform image cannot read engine/ at runtime, and a bundled module is
// the one place Next is guaranteed to ship with the server. The spark is never
// retyped: rerun this after a kit update, and tests/passes-art.test.js fails
// until you do.
//
//   node scripts/sync-pass-brand-assets.mjs
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const platformRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const kitLogos = path.resolve(platformRoot, "../engine/dgtl-brand-kit/assets/logos");
const out = path.join(platformRoot, "lib/passes/brandAssets.js");

const spark = await readFile(path.join(kitLogos, "spark.svg"), "utf8");
// The white-and-gold wordmark: the Wallet logo.png on a dark card face.
const wordmark = await readFile(path.join(kitLogos, "logo-white-gold.svg"), "utf8");
await writeFile(
  out,
  `// GENERATED by scripts/sync-pass-brand-assets.mjs from
// engine/dgtl-brand-kit/assets/logos/{spark,logo-white-gold}.svg. Do not edit
// by hand: tests/passes-art.test.js fails if this drifts from the kit.
export const SPARK_SVG = ${JSON.stringify(spark)};
export const WORDMARK_SVG = ${JSON.stringify(wordmark)};
`
);
console.log(`wrote ${path.relative(platformRoot, out)} (spark ${spark.length} bytes, wordmark ${wordmark.length} bytes)`);
